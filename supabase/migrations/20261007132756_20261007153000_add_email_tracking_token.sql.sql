/*
# Add private email tracking tokens

1. Modified Tables
- `email_logs.tracking_token` (uuid): unique opaque token used by the email status endpoint.

2. Security
- The token is generated by the database and indexed for constant-time lookup.
- It is not used as an authorization grant for the application; it only identifies the email record receiving a provider callback or tracking-pixel request.
- Existing row-level security policies remain unchanged.

3. Important Notes
- This migration is additive and preserves all existing email records.
- Existing records receive tokens automatically so they can be used by later workflows.
*/

ALTER TABLE email_logs
  ADD COLUMN IF NOT EXISTS tracking_token uuid NOT NULL DEFAULT gen_random_uuid();

CREATE UNIQUE INDEX IF NOT EXISTS idx_email_logs_tracking_token
  ON email_logs(tracking_token);